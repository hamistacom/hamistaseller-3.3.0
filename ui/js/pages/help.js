function section(id, title, ic, body, open) {
  return h("details", { class: "card help-sec", id: `help-${id}`, open }, h("summary", {}, h("span", { class: "ic-box" }, icon(ic, "sm")), h("h2", {}, title)), h("div", { class: "help-body" }, body));
}

export async function render(root, params) {
  const topic = params.topic || "";
  const report = h("div", { class: "stack tight" });
  const makeReport = async (btn) => {
    btn.disabled = true;
    const path = await safe(invoke("support_report"));
    btn.disabled = false;
    if (!path) return;
    clear(
      report,
      h("div", { class: "callout ok" }, icon("check"), h("div", { class: "small" }, "فایل گزارش ساخته شد. آن را در تلگرام برای پشتیبانی بفرستید. رمزها و کلیدها در آن نیستند.")),
      h("div", { class: "code-box" }, path),
      h(
        "div",
        { class: "row wrap" },
        h("button", { class: "btn sm", type: "button", onclick: () => safe(invoke("reveal", { path })) }, icon("folder", "sm"), "نمایش فایل"),
        h("button", { class: "btn sm", type: "button", onclick: () => copy(path, "مسیر کپی شد") }, icon("copy", "sm"), "کپی مسیر"),
      ),
    );
  };
  const pageList = Object.entries(PAGES)
    .filter(([k]) => k !== "megabank" || app.info.license?.megabank)
    .map(([k, [t, d]]) => h("div", { class: "help-item", id: `help-page-${k}` }, h("div", { class: "row" }, h("b", { class: "grow" }, t), h("button", { class: "link small", type: "button", onclick: () => go(k) }, "رفتن به صفحه")), h("p", {}, d)));
  root.append(
    h(
      "div",
      { class: "stack help" },
      section(
        "start",
        "شروع سریع",
        "sparkle",
        h("ol", { class: "steps" }, QUICK.map(([t, d]) => h("li", {}, h("b", {}, t), h("span", {}, d)))),
        !topic,
      ),
      section("pages", "راهنمای بخش‌ها", "book", pageList, !!topic && PAGES[topic]),
      section("sources", "استخراج دقیق‌تر", "map", SOURCES.map(([t, d]) => h("div", { class: "help-item" }, h("b", {}, t), h("p", {}, d))), topic === "scan"),
      section("glossary", "واژه‌نامه", "info", h("dl", { class: "kv glossary" }, GLOSSARY.map(([k, v]) => [h("dt", {}, k), h("dd", {}, v)])), false),
      section("problems", "خطاهای رایج و راه‌حل", "alert", h("div", { class: "grid-2" }, PROBLEMS.map(([t, d]) => h("div", { class: "help-item problem" }, h("b", {}, t), h("p", {}, d)))), topic === "problems"),
      section(
        "support",
        "پشتیبانی",
        "chat",
        [
          h("p", { class: "small muted" }, "اگر مشکلی حل نشد، یک گزارش بسازید و همراه توضیح کوتاه برای پشتیبانی هامیستا بفرستید."),
          h(
            "div",
            { class: "row wrap" },
            h("button", { class: "btn primary", type: "button", onclick: (e) => makeReport(e.currentTarget) }, icon("download", "sm"), "ساخت گزارش برای پشتیبانی"),
            h("button", { class: "btn", type: "button", onclick: () => safe(invoke("open_url", { url: "https://t.me/hamistaa" })) }, icon("telegram", "sm"), "پشتیبانی در تلگرام"),
            h("button", { class: "btn ghost", type: "button", onclick: () => safe(invoke("open_url", { url: "https://hamista.ir" })) }, icon("globe", "sm"), "hamista.ir"),
          ),
          report,
        ],
        topic === "support",
      ),
    ),
  );
  if (topic && PAGES[topic]) {
    const el = root.querySelector(`#help-page-${topic}`);
    if (el) {
      el.classList.add("hl");
      setTimeout(() => el.scrollIntoView({ block: "center" }), 50);
    }
  }
}
