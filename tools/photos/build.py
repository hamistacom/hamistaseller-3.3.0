# picks (key -> candidate index) -> ui/img/<key>.webp (1100x360 banner) + <key>-c.webp (600x450 card),
# ui/js/photo-credits.js and ui/img/CREDITS.md (CC attribution: title, author, source, licence).
import json, os, subprocess, sys
UI = "/home/claude/hamista-seller/ui"
cand = json.load(open("cand.json")); picks = json.load(open("picks.json")) if os.path.exists("picks.json") else {}
os.makedirs(f"{UI}/img", exist_ok=True)
credits, md = {}, ["# Photo credits", "", "Photos are used under their Creative Commons licences (found via Openverse — Flickr — and Wikimedia Commons). Cropped and resized.", ""]
ALIAS = {"k-furniture": "m-furniture", "m-mobile": "k-mobile", "k-realestate": "k-construction", "m-cafe": "k-cafe"}  # one photo serves both
for key in sorted(set(cand) | set(ALIAS)):
    src_key = ALIAS.get(key, key); lst = cand.get(src_key) or []
    if not lst: continue
    i = picks.get(src_key, 0)
    if i is None or i < 0: continue
    m = next((c for c in lst if c["i"] == i), lst[0])
    src = f"cand/{src_key}_{m['i']}.jpg"
    if not os.path.exists(src): continue
    grav = {"p-isfahan": "south"}.get(key, "center")
    subprocess.run(["convert", src, "-auto-orient", "-resize", "1100x360^", "-gravity", grav, "-extent", "1100x360", "-strip", "-quality", "62", f"{UI}/img/{key}.webp"], check=True)
    if key[0] in "km":
        subprocess.run(["convert", src, "-auto-orient", "-resize", "600x450^", "-gravity", grav, "-extent", "600x450", "-strip", "-quality", "64", f"{UI}/img/{key}-c.webp"], check=True)
    who = (m.get("creator") or "").strip() or "unknown"
    credits[key] = f"{who} · {m['license'].strip()}"
    md.append(f"- **{key}** — “{m['title']}” by {who}, {m['license'].strip()} — {m['landing']}")
open(f"{UI}/js/photo-credits.js", "w").write("// generated by the photo build script — author and licence of each bundled photo\nexport const CREDITS = " + json.dumps(credits, ensure_ascii=False, indent=1) + ";\n")
open(f"{UI}/img/CREDITS.md", "w").write("\n".join(md) + "\n")
print(len(credits), "photos;", sum(os.path.getsize(f"{UI}/img/{f}") for f in os.listdir(f"{UI}/img") if f.endswith(".webp")) // 1024, "KB")
